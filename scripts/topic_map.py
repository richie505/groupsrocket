def main() -> None:
    TOPICS_DIR.mkdir(parents=True, exist_ok=True)
    ok = True
    for p in sorted(SHEETS_DIR.glob("*.json")):
        notes = load_json(p)
        subject, ids = notes["subject"], [s["id"] for s in notes["sheets"]]
        topics = [{"title": t, "sheets": s.split()} for t, s in T[subject]]
        placed = [s for t in topics for s in t["sheets"]]
        missing = [i for i in ids if i not in placed]
        extra = sorted({s for s in placed if s not in ids})
        dup = sorted({s for s in placed if placed.count(s) > 1})
        if missing or extra or dup:
            ok = False
            print(f"{subject}: missing {missing} unknown {extra} repeated {dup}")
            continue
        save_json(TOPICS_DIR / f"{slugify(subject)}.json", {"subject": subject, "topics": topics})
        print(f"{subject}: {len(ids)} sheets -> {len(topics)} topics")
    raise SystemExit(0 if ok else 1)


if __name__ == "__main__":
    main()
